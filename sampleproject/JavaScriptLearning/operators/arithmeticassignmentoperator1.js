// Arithmetic Assignment Operator
// Addition Assignment Operator
let a=30
a+=10
console.log(a)  // 40
a=a+5
console.log(a)  // 45
// Substration Assignment Operator
let b=10
b-=2
console.log(b)  // 8
b=b-3
console.log(b)  // 5
// Multiplication Assignment Operator
let c=12
c*=5
console.log(c)  // 60
c=c*3
console.log(c)  //180
//Division Assignment Operator
let d=45
d/=5
console.log(d)   //9
d=d/3           
console.log(d)   //3
//Modulus Assignment Operator
let e=21
e%=2
console.log(e)  //1